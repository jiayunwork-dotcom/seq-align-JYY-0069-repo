// BlosumScore returns the BLOSUM62 score for two amino acids.
func BlosumScore(a, b byte) int {
	key := string([]byte{a, b})
	if s, ok := BLOSUM62[key]; ok {
		return s
	}
	return -4 // default for unknown
}

// ProteinScheme returns a scoring scheme using BLOSUM62 lookup.
func ProteinScheme(gapOpen, gapExtend int) Scheme {
	return Scheme{
		Match:     4,  // diagonal identity average
		Mismatch:  -1, // average off-diagonal
		GapOpen:   gapOpen,
		GapExtend: gapExtend,
	}
}
